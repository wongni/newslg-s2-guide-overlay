// 표시 라벨은 키와 같다 (정찰앱 이름 그대로)
export const TEAM_DISPLAY: Record<TeamName, string> = Object.fromEntries(
  TEAMS.map((t) => [t, t])
) as Record<TeamName, string>;

export const DECK_SLUG: Record<TeamName, string | null> = Object.fromEntries(
  TEAMS.map((t) => [t, null])
) as Record<TeamName, string | null>;

export const DECK_BASE_URL = "https://cheonha-deck.xyz/decks";

export function deckUrl(team: TeamName): string | null {
  const slug = DECK_SLUG[team];
  return slug ? `${DECK_BASE_URL}/${encodeURIComponent(slug)}` : null;
}

